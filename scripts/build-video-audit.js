#!/usr/bin/env node
/* eslint-disable no-console */
/**
 * Renders youtube-uploads/audit/video-audit.json into a Markdown table.
 *
 *   node scripts/build-video-audit.js
 *   node scripts/build-video-audit.js --from youtube-uploads/audit/video-audit.json --out youtube-uploads/audit/video-audit.md
 */
const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.join(__dirname, '..');

function arg(name, fallback) {
  const index = process.argv.indexOf(`--${name}`);
  return index > -1 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

const source = path.resolve(REPO_ROOT, arg('from', 'youtube-uploads/audit/video-audit.json'));
const target = path.resolve(REPO_ROOT, arg('out', 'youtube-uploads/audit/video-audit.md'));

function statusOf(item) {
  if (item.action.startsWith('Publish')) return 'PUBLISH';
  if (item.action.startsWith('Optional')) return 'OPTIONAL';
  if (item.action.startsWith('Finish')) return 'FINISH';
  if (item.action.startsWith('Hold')) return 'HOLD';
  if (item.action.startsWith('Reference')) return 'REFERENCE';
  return 'ARCHIVE';
}

function escapeCell(value) {
  return String(value).replace(/\|/g, '\\|');
}

const audit = JSON.parse(fs.readFileSync(source, 'utf8'));
// `n` is assigned newest-first when the audit is written; it is the stable order.
const items = [...audit.items].sort((a, b) => a.n - b.n);

const byStatus = items.reduce((acc, item) => {
  const status = statusOf(item);
  acc[status] = (acc[status] || 0) + 1;
  return acc;
}, {});

const lines = [];
lines.push('# Video audit — everything created after 8 Nov 2026');
lines.push('');
lines.push(`Window: **${audit.window.from} → ${audit.window.to}** (${audit.window.timezone}). Source: Google Drive video files, newest first.`);
lines.push('');
lines.push(`**${audit.totals.renders} renders · ${audit.totals.finals} finals · ${audit.totals.working} working cuts · ${audit.totals.duplicates} duplicates.**`);
lines.push('');
lines.push('| Status | Count |');
lines.push('| --- | --- |');
for (const status of ['PUBLISH', 'FINISH', 'HOLD', 'OPTIONAL', 'REFERENCE', 'ARCHIVE']) {
  if (byStatus[status]) lines.push(`| ${status} | ${byStatus[status]} |`);
}
lines.push('');
lines.push('## Every render');
lines.push('');
lines.push('| # | Created (IST) | Project | File | Shape | Length | Role | Verdict | Action |');
lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
for (const item of items) {
  lines.push([
    item.n,
    `${item.dateIST} ${item.timeIST}`,
    item.project,
    `\`${escapeCell(item.file)}\``,
    `${item.aspect} ${item.res}`,
    item.duration,
    item.type,
    escapeCell(item.verdict),
    `**${statusOf(item)}** — ${escapeCell((item.action.split('—').slice(1).join('—').trim()) || 'do not upload')}`
  ].join(' | ').replace(/^/, '| ').replace(/$/, ' |'));
}
lines.push('');
lines.push('## What goes out next');
lines.push('');
lines.push('### Batch 2 — Shorts');
lines.push('');
lines.push('| File | Schedule | Why |');
lines.push('| --- | --- | --- |');
for (const row of audit.nextBatch.batch2Shorts) {
  lines.push(`| \`${escapeCell(row.file)}\` | ${row.when} | ${escapeCell(row.why)} |`);
}
lines.push('');
lines.push('### Batch 2 — regular (16:9 / long-form)');
lines.push('');
lines.push('| File | Schedule | Why |');
lines.push('| --- | --- | --- |');
for (const row of audit.nextBatch.batch2Regular) {
  lines.push(`| \`${escapeCell(row.file)}\` | ${row.when} | ${escapeCell(row.why)} |`);
}
lines.push('');
lines.push('### Needs work before it can ship');
lines.push('');
for (const row of audit.nextBatch.needsWork) lines.push(`- ${row}`);
lines.push('');
lines.push('### Archive (do not upload — duplicates and working cuts)');
lines.push('');
for (const row of audit.nextBatch.archive) lines.push(`- ${row}`);
lines.push('');
lines.push('*Generated by `scripts/build-video-audit.js` from `video-audit.json`.*');
lines.push('');

fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, lines.join('\n'));
console.log(`Wrote ${path.relative(REPO_ROOT, target)} — ${items.length} items, statuses: ${JSON.stringify(byStatus)}`);
